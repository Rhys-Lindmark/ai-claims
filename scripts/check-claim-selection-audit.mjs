import assert from 'node:assert/strict';
import fixture from '../data/claim-selection-audit-fixture.json' with { type: 'json' };
import { selectionAuditSummary, validateClaimSelectionAudit } from '../lib/claim-selection-audit.ts';
import samplingFixture from '../data/claim-selection-sampling-frame-fixture.json' with { type: 'json' };
import { claimSelectionSamplingDecision, validateClaimSelectionSamplingFrame } from '../lib/claim-selection-sampling.ts';
import calibrationFixture from '../data/claim-selection-calibration-fixture.json' with { type: 'json' };
import { claimSelectionCalibrationDecision, validateClaimSelectionCalibration } from '../lib/claim-selection-calibration.ts';
import driftFixture from '../data/claim-selection-drift-fixture.json' with { type: 'json' };
import { claimSelectionDriftDecision, validateClaimSelectionCalibrationBatches } from '../lib/claim-selection-drift.ts';
import remediationFixture from '../data/claim-selection-remediation-fixture.json' with { type: 'json' };
import { claimSelectionRemediationDecision, validateClaimSelectionRemediations } from '../lib/claim-selection-remediation.ts';
import historyFixture from '../data/analysis-history-fixture.json' with { type: 'json' };
import resumptionFixture from '../data/publication-resumption-fixture.json' with { type: 'json' };
import { publicationResumptionDecision } from '../lib/publication-resumption.ts';
import correctionFeedFixture from '../data/correction-event-feed-fixture.json' with { type: 'json' };
import { validateCorrectionEventFeed } from '../lib/correction-event-feed.ts';

assert.deepEqual(validateClaimSelectionAudit(fixture.samples), []);
const summary = selectionAuditSummary(fixture.samples);
assert.deepEqual(summary.counts, { true_positive: 2, false_positive: 2, false_negative: 1, true_negative: 1 });
assert.equal(summary.sample_size, 6);
assert.equal(summary.sample_precision, 0.5);
assert.equal(summary.sample_recall, 2 / 3);
assert.deepEqual(validateClaimSelectionSamplingFrame(samplingFixture), []);
const samplingDecision = claimSelectionSamplingDecision(samplingFixture);
assert.equal(samplingDecision.metrics_publishable, false);
assert.match(samplingDecision.blockers.join(' '), /12 are required/);
assert.match(samplingDecision.blockers.join(' '), /Unknown \/ overlap/);
assert.match(samplingDecision.blockers.join(' '), /Low confidence/);
assert.deepEqual(validateClaimSelectionCalibration(calibrationFixture.records), []);
const calibrationDecision = claimSelectionCalibrationDecision(calibrationFixture.records);
assert.equal(calibrationDecision.denominator_publishable, false);
assert.equal(calibrationDecision.summary.agreements, 2);
assert.equal(calibrationDecision.summary.disagreements, 2);
assert.equal(calibrationDecision.summary.unresolved.length, 1);
assert.deepEqual(validateClaimSelectionCalibrationBatches(driftFixture.batches), []);
const driftDecision = claimSelectionDriftDecision(driftFixture.batches);
assert.equal(driftDecision.methodology_review_required, true);
assert.equal(driftDecision.denominator_publication_paused, true);
assert.equal(driftDecision.latest_agreement, 0.65);
assert.equal(driftDecision.rolling_three_batch_agreement, 0.8);
assert.ok(Math.abs(driftDecision.change_from_previous - (-0.2)) < Number.EPSILON * 4);
assert.deepEqual(validateClaimSelectionRemediations(remediationFixture.records), []);
const remediationDecision = claimSelectionRemediationDecision(remediationFixture.records);
assert.equal(remediationDecision.denominator_publication_resumes, false);
assert.deepEqual(remediationDecision.blockers, ['remediation-overlap is in progress.']);
const resumptionDecision = publicationResumptionDecision(historyFixture.versions, resumptionFixture);
assert.equal(resumptionDecision.can_resume_publication, true);
assert.equal(resumptionDecision.previous_public_version_id, 'analysis-demo-v3');
assert.equal(resumptionDecision.new_public_version_id, 'analysis-demo-v4');
assert.equal(historyFixture.versions.at(-1).version_id, 'analysis-demo-v3');
assert.deepEqual(validateCorrectionEventFeed(correctionFeedFixture.events), []);
const leakingEvent = { ...correctionFeedFixture.events[0], truth_score_0_100: 84 };
assert.match(validateCorrectionEventFeed([leakingEvent])[0], /must not carry score fields/);
console.log('Claim-selection audit fixture passed.');
